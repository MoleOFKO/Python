"""
Python meth module
- math module is a built-in python library that provides mathematical functions 
and constants for performing advanced calculations
- import the module first
Syntax : import math
"""

# 1. math.sqrt() - square root : returns the square root of a number
# Syntax : math.sqrt(number)
import math
print(int(math.sqrt(25)))

# 2. math.pow() - power : rises a number to a given power
# import math
print(math.pow(2, 3))


# 3. math.ceil() - round up : rounds number up to the nearest integer
print(math.ceil(3.14159))


# 4. math.floor() - round down : rounds a number down to the nearest integer
print(math.floor(3.14159))


# 5. math.factorial() - factorial : returns the factorial of number
print(math.factorial(6))


# 6. math.pi - pi constant : returns the value of pi
print(math.pi)


# 7. math.e - euler's number : returns Euler's constant
print(math.e)


# 8. math.sin() - sine : calculate the sine of an angle (in radians)
print(math.sin(90))
print(math.sin(math.radians(90)))


# 9. math.cos() - cosine: calculate the cosine of an angle (in radians)
print(math.cos(90))
print(math.cos(math.radians(90)))



#  10. math.tan() - tangent : calculate the tangent of an angle (in radians)
print(math.tan(90))
print(math.tan(math.radians(90)))


# 11. math.radians() - degrees to radians : convert degrees to radians
print(math.radians(90))


# 12. math.degrees() - radians to degrees : convert radians to degrees
print(math.degrees(math.pi))


# 13. math.log() - natural logarithm : calculate the natural logarithm of a number
print(math.log(10))


# 14. math.log10() - base 10 logarithm : calculate the base 10 logarithm of a number
print(math.log10(100))


# 15. math.fabs() - absolute value : returns the absolute (positive) value of a number
print(math.fabs(-4))
print(math.fabs(9))


