#1. abs() - absolute : returns the positive values of a number
# Syntax: abs(number)
print(abs(-4))
print(abs(9))

#2. pow() - power : return a number to a specified power
# syntax : pow(base, exponent)
print(pow(2, 3)) 
print(pow(-3, 2))


#3. max() - maximum : return the largest value
# Syntax : max(numbers)
print(max(23, 15, 29, 40))
print(max(-34, -67, -2, -1))


#4. min() - minimum : return the smallest value
# Syntax : min(numbers)
print(min(3, 5, 6, 1, 8))
print(min(-3, -5, -6, -1, -8))


#5. round() - round a number to the nearest integer or specified decimal places
# Syntax : round(numbers)
print(round(3.14159))
print(round(3.14159))
print(round(3.14159, 2))


#6. sum() - sum of numbers: adds all elements in an iterable
numbers = [1, 2, 3, 4, 5]
print(sum(numbers))


#7. divmod() - quotient and remainder
# Syntax : divmod(dividend, divisor)
print(divmod(10, 3))
