"""**Step-5 : Format Association Rules**"""

def format_rules(rules):
  results = []

  #Fo through every rules
  for _, row in rules.iterrows():

    #Convert product into text
    antecedent = ",".join(row("antecedents"))
    consequent = ",".join(row("consequents"))

    #Create one rwo result
    results.append({
        "If Costomer Buys" : antecedent,
        "Then Customer May Buy" : consequent,
        "Support" : round(row["support"], 3),
        "Confidence" : round(row["confidence"], 3),
        "Lift" : round(row["lift"], 3)
    })

    #Crate results to a DataFrame
    create_dataframe(results)

