"""**Step-4 : Convert Transactions to DataFrame**"""

def create_dataframe(transactions):

  #Create a TaransactionEncoder
  encoder = TransactionEncoder()

  #Convert transactions into True/False values.
  encoded = encoder.fit(transactions).transform(transactions)

  #Craete a pandas dataframe
  dataframe = pd.DataFrame(
      encoded,
      columns = encoder.columns_
  )

  return dataframe

#Create the default dataset
